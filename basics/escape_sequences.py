#Escape Sequences


# Can't have single quotes inside single quotes, so we use double quotes to define the string.
story_desc = "It's a touching story"
print(story_desc)


# Can use \ as an escape sequence
story_desc = 'It\'s a touching story'
print(story_desc)

#newline
story_desc = "It's a \n touching \n story"
print(story_desc)
